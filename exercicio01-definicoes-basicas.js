function definicoesBasicas() {
  console.log("1a) Erro: é uma falha, defeito ou resultado inesperado no programa (de sintaxe, lógica ou execução) que faz o código não se comportar como o desejado.");
  console.log("1b) Exceção: é um evento anormal que ocorre durante a execução e interrompe o fluxo normal, sendo representado por um objeto (ex.: Error) que pode ser lançado (throw) e capturado (try...catch).");
  console.log("1c) Diferença: em linguagem natural, 'erro' é qualquer coisa que deu errado (inclusive um cálculo de lógica incorreto). Em JavaScript, 'exceção' é o mecanismo concreto de sinalizar um problema via throw; nem todo erro gera exceção.");
}
